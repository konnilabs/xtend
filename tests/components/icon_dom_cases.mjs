// Shared executable cases: jsdom in the component CI gate and a real-browser fixture.
import { createComponentStyle } from '../../components/style-nonce.js';
import { createSvgElement } from '../../components/icon-dom.js';
export async function runIconDomCases(document) {
  const checks = [], errors = [], view = document.defaultView;
  const check = (name, condition) => { checks.push({name, passed:Boolean(condition)}); if (!condition) errors.push(name); };
  const make = (tag, attrs = {}) => {
    const node = document.createElement(tag);
    for (const [name, value] of Object.entries(attrs)) node.setAttribute(name, value);
    document.body.append(node);
    return node;
  };
  const payload = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" onload="window.__iconExecuted=true" fill="red"><path d="M1 1L4 4" onclick="window.__iconExecuted=true" fill="url(https://example.invalid/paint)"/><script>window.__iconExecuted=true</script><foreignObject><img onerror="window.__iconExecuted=true"/></foreignObject><image href="https://example.invalid/track"/><g><circle cx="5" cy="5" r="2"/></g></svg>';
  view.XTend.icons.register({id:'safe-dom-a',icons:{custom:payload,same:'M1 1L2 2'}});
  view.XTend.icons.register({id:'safe-dom-b',icons:{same:'M3 3L4 4'}});
  const icon = make('x-icon',{name:'custom',pack:'safe-dom-a',label:'Custom icon'});
  const root = icon.shadowRoot.querySelector('[part="root"]');
  const svg = root.querySelector('svg');
  check('XIcon constructs a native shell with the public root and SVG parts', Boolean(svg) && svg.getAttribute('viewBox')==='0 0 32 32');
  check('SVG geometry survives, executable and external nodes do not', svg.querySelectorAll('path,circle').length===2 && !svg.querySelector('script,foreignObject,img,image,[onload],[onclick],[href]') && !svg.querySelector('path').hasAttribute('fill'));
  check('labeled icons preserve image semantics', icon.getAttribute('role')==='img' && icon.getAttribute('aria-label')==='Custom icon');
  icon.setAttribute('decorative','true');
  check('decorative icons retain their stable root and hide from assistive tech', icon.getAttribute('aria-hidden')==='true' && root===icon.shadowRoot.querySelector('[part="root"]'));
  for (const src of ['javascript:alert(1)',' java\nscript:alert(1)','vbscript:alert(1)','data:text/html,<svg onload=alert(1)>']) {
    icon.setAttribute('src',src);
    check('XIcon refuses unsafe URL '+src.split(':')[0], !root.querySelector('img,svg') && icon.snapshot().mode==='missing');
  }
  icon.removeAttribute('src');
  const button = make('x-button',{label:'<img onerror=alert(1)>',icon:payload});
  const native = button.shadowRoot.querySelector('button'), slot = button.shadowRoot.querySelector('slot');
  const buttonSvg = button.shadowRoot.querySelector('[part="icon"] svg');
  check('legacy button SVG uses the same geometry allowlist', Boolean(buttonSvg) && !buttonSvg.querySelector('script,foreignObject,image,[onclick]') && !buttonSvg.hasAttribute('onload') && buttonSvg.getAttribute('fill')==='red');
  check('fallback button labels stay literal text', button.shadowRoot.querySelector('[part="label-fallback"]').textContent==='<img onerror=alert(1)>' && !button.shadowRoot.querySelector('[part="label"] img'));
  button.setAttribute('icon','/missing" onerror="window.__iconExecuted=true');
  const img = button.shadowRoot.querySelector('[part="icon"] img');
  check('URL quotes cannot create additional image attributes', Boolean(img) && !img.hasAttribute('onerror') && img.getAttribute('src').includes('"'));
  for (const src of ['javascript:alert(1)','vbscript:alert(1)','data:text/html,<script>']) {
    button.setAttribute('icon',src);
    check('XButton refuses unsafe URL '+src.split(':')[0], button.shadowRoot.querySelector('[part="icon"]').children.length===0);
  }
  button.setAttribute('icon','<svg><path d="M1 1"');
  check('malformed SVG contributes no geometry', !button.shadowRoot.querySelector('[part="icon"] path'));
  button.setAttribute('icon','<svg><!DOCTYPE svg [<!ENTITY test "text">]><path d="M1 1"/></svg>');
  check('DTD and entity markup contributes no geometry', !button.shadowRoot.querySelector('[part="icon"] path'));
  button.setAttribute('icon-name','same');button.setAttribute('icon-pack','safe-dom-a');
  button.setAttribute('icon-pack','safe-dom-b');button.setAttribute('icon-name','search');
  button.setAttribute('icon-pack','core');button.setAttribute('icon-name','same');button.setAttribute('icon-pack','safe-dom-b');
  await Promise.resolve();
  const packed = button.shadowRoot.querySelector('x-icon');
  check('rapid name and pack changes commit only the current icon', packed.getAttribute('name')==='same' && packed.getAttribute('pack')==='safe-dom-b' && packed.shadowRoot.querySelector('path').getAttribute('d')==='M3 3L4 4');
  native.focus();button.setAttribute('loading','');button.removeAttribute('loading');button.setAttribute('label','Updated label');
  check('non-icon updates preserve icon, native control and slot identity', button.shadowRoot.querySelector('x-icon')===packed && native===button.shadowRoot.querySelector('button') && slot===button.shadowRoot.querySelector('slot'));
  native.focus();button.setAttribute('variant','danger');
  check('variant updates preserve keyboard focus', button.shadowRoot.activeElement===native);
  const content = document.createElement('span');content.textContent='Slotted content';button.append(content);
  await Promise.resolve();
  check('default slot still projects host content', slot.assignedNodes().includes(content));
  let clicks=0;button.addEventListener('button-interaction',event=>{if(event.detail.type==='click')clicks++;});native.click();
  check('native button activation remains available',clicks===1);
  button.setAttribute('disabled','');native.click();
  check('disabled button cannot activate',clicks===1 && native.disabled);
  button.remove();button.setAttribute('icon-pack','safe-dom-a');document.body.append(button);
  check('reconnected button uses its current icon', button.shadowRoot.querySelector('x-icon').getAttribute('pack')==='safe-dom-a');
  const spinner = make('x-spinner',{type:'dots','aria-label':'Searching'});
  check('dots spinner materializes without an HTML sink', spinner.shadowRoot.querySelectorAll('.dot').length===3);
  spinner.setAttribute('type','circle');spinner.setAttribute('type','dots');spinner.pause();spinner.resume();
  check('spinner transitions clear prior geometry and release paused state', spinner.shadowRoot.querySelectorAll('.dot').length===3 && !spinner.hasAttribute('paused'));
  check('component stylesheet nonces remain host-issued', [icon,button].every(node => node.shadowRoot.querySelector('style').nonce==='iconSmokeNonce123'));
  const nonceSource=document.getElementById('xtend-page-data');
  nonceSource.nonce='invalid nonce "';
  const invalidStyle=createComponentStyle(':host { color: red; }',document);
  check('invalid nonce values are not authorized', !invalidStyle.hasAttribute('nonce'));
  nonceSource.nonce='iconSmokeNonce123';
  const other=document.implementation.createHTMLDocument('Other document');
  const owned=createSvgElement({nodes:[{tag:'path',attrs:{d:'M1 1L2 2',onclick:'alert(1)'}}]},{document:other});
  check('native SVG nodes belong to the supplied document', owned.ownerDocument===other && owned.firstElementChild.ownerDocument===other && !owned.firstElementChild.hasAttribute('onclick'));
  check('icon payloads never execute', view.__iconExecuted!==true);
  const hostile='<img src=x onerror="window.__iconExecuted=true">';
  const section=make('x-section',{label:hostile});
  check('section labels remain an attribute value', section.shadowRoot.querySelector('[role="region"]').getAttribute('aria-label')===hostile && !section.shadowRoot.querySelector('img'));
  const dialog=make('x-dialog',{title:hostile,open:'',overlay:''});
  await Promise.resolve();
  check('dialog titles remain literal text', dialog.shadowRoot.querySelector('[part="title"]').textContent===hostile && !dialog.shadowRoot.querySelector('img'));
  const dialogContent=document.createElement('p');dialogContent.textContent='Dialog content';dialog.append(dialogContent);
  check('dialog content and actions remain public slots', Boolean(dialog.shadowRoot.querySelector('slot')) && Boolean(dialog.shadowRoot.querySelector('slot[name="actions"]')));
  dialog.close();await Promise.resolve();
  check('dialog close releases its open state', !dialog.hasAttribute('open'));
  const toast=make('x-toast',{type:'success',duration:'0'});
  check('toast retains accessible status and native close SVG', toast.shadowRoot.querySelector('[role="status"]') && toast.shadowRoot.querySelector('[part="close-icon control icon"]'));
  toast.shadowRoot.querySelector('button').click();
  check('toast close dismisses without HTML writes',toast.hidden || !toast.isConnected || toast.snapshot().dismissed);
  const alert=make('x-alert',{type:'warning',closable:'',duration:'0'});
  check('alert retains live semantics and native close SVG', alert.shadowRoot.querySelector('[role="alert"]') && alert.shadowRoot.querySelector('[part="close-icon control icon"]'));
  const toggle=make('x-toggle',{label:'Temperature units'}),input=toggle.shadowRoot.querySelector('input');let changes=0;
  toggle.addEventListener('toggle-changed',()=>changes++);input.click();input.click();
  check('native toggle activation emits once per change', changes===2 && !toggle.checked && input.getAttribute('role')==='switch');
  check('toggle on/off labels and helper slots remain present', toggle.shadowRoot.querySelector('slot[name="on-label"]').textContent==='I' && toggle.shadowRoot.querySelector('slot[name="off-label"]').textContent==='O' && toggle.shadowRoot.querySelector('slot[name="hint"]'));
  for(const node of [icon,button,spinner,section,dialog,toast,alert,toggle])node.remove();
  return {status:errors.length?'failed':'passed',checks,errors};
}

'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { createClassicAstSchema } = require('../tools/rmt-language/classic-ast-rules');
const root = path.resolve(__dirname, '..');
const schema = createClassicAstSchema();
function typeOf(value) {
  if (value.$ref) return value.$ref.split('/').pop();
  // Reuse the public discriminator type. The formal JSON schema owns the full
  // recursive shape; a second, expanded syntactic approximation adds no proof.
  if (Object.hasOwn(value, 'const')) return value.const === schema.$id ? 'RmtClassicAstSchema' : JSON.stringify(value.const);
  if (value.enum) return value.enum.map(item => JSON.stringify(item)).join(' | ');
  if (value.anyOf || value.oneOf) return (value.anyOf || value.oneOf).map(typeOf).join(' | ');
  if (Array.isArray(value.type)) return value.type.map(type => typeOf({ type })).join(' | ');
  if (value.type === 'array') return `Array<${typeOf(value.items)}>`;
  if (value.type === 'object') return `{ ${Object.entries(value.properties).map(([key, child]) =>
    `${JSON.stringify(key)}${value.required.includes(key) ? '' : '?'}: ${typeOf(child)};`).join(' ')} }`;
  return { string: 'string', boolean: 'boolean', number: 'number', integer: 'number', null: 'null' }[value.type];
}
const types = '// Generated by scripts/generate_rmt_classic_contract.js from curated Classic AST rules.\n'
  + '// Legacy Rmt*/vnext discriminators are wire-compatible names, not a release label.\n'
  + "import type { RMT_CLASSIC_AST_SCHEMA } from './classic-parser';\n"
  + 'export type RmtClassicAstSchema = typeof RMT_CLASSIC_AST_SCHEMA;\n'
  + Object.entries(schema.definitions).map(([name, value]) => `export type ${name} = ${typeOf(value)};`).join('\n')
  + '\nexport type RmtClassicAst = RmtVNextDocument;\n';
const outputs = {
  'tools/rmt-language/contracts/classic-ast.v1.schema.json': JSON.stringify(schema, null, 2) + '\n',
  'tools/rmt-language/classic-ast-types.d.ts': types
};
for (const [file, content] of Object.entries(outputs)) {
  const absolute = path.join(root, file);
  if (process.argv.includes('--write')) { fs.mkdirSync(path.dirname(absolute), { recursive: true }); fs.writeFileSync(absolute, content); }
  else if (!fs.existsSync(absolute) || fs.readFileSync(absolute, 'utf8') !== content) throw new Error(`Classic contract drift: ${file}. Regenerate with --write.`);
}
console.log(JSON.stringify({ nodeTypes: Object.keys(schema.definitions).filter(name => name.startsWith('Rmt')).length, outputs: Object.keys(outputs) }));
